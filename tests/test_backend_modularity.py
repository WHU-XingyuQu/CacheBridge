def test_config_load_is_explicit_and_paths_are_relative_to_its_file(tmp_path):
    path = tmp_path / "runtime.json"
    path.write_text(
        json.dumps(
            dict(
                source_model="source",
                target_model="target",
                mapper_descriptor="weights/mapper.json",
                engine_path="engine",
            )
        )
    )
    config = RuntimeConfig.load(path)
    assert config.source_model == tmp_path / "source"
    assert config.mapper_descriptor == tmp_path / "weights/mapper.json"
    assert config.engine_path == tmp_path / "engine"
    # No model, engine or weight files are read by the config loader.
    assert not config.source_model.exists()
    for change in (
        dict(tensor_parallel_size=2),
        dict(source_port=34631),
        dict(model_pair="unimplemented"),
        dict(pool_tokens=0),
    ):
        path.write_text(
            json.dumps(
                dict(
                    source_model="s", target_model="t", mapper_descriptor="m", **change
                )
            )
        )
        with pytest.raises(ValueError):
            RuntimeConfig.load(path)


def test_all_runtime_modules_import_without_config_or_engine(monkeypatch):
    monkeypatch.delenv("CACHEBRIDGE_CONFIG", raising=False)
    from cachebridge.backends.sglang import runtime

    for module in pkgutil.iter_modules(runtime.__path__):
        importlib.import_module(runtime.__name__ + "." + module.name)
    assert "sglang" not in sys.modules


