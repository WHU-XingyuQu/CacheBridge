def test_runtime_uses_one_shared_mapper_implementation():
    from cachebridge.backends.sglang import runtime

    for path in Path(runtime.__file__).parent.rglob("*.py"):
        tree = ast.parse(path.read_text())
        assert not any(
            isinstance(n, ast.ClassDef) and n.name == "PageMapper"
            for n in ast.walk(tree)
        )
    from cachebridge.online.mapper import PageMapper as old
    from cachebridge.online.mapping import PageMapper as current

    assert old is current


def test_prepare_reproduces_pinned_engine_and_keeps_submodule_clean(tmp_path):
    source = ROOT / "third_party/sglang"
    if not (source / ".git").exists():
        pytest.skip(
            "Initialize the pinned SGLang submodule to run dependency preparation"
        )
    before = subprocess.check_output(
        ["git", "-C", str(source), "status", "--porcelain"]
    )
    output = prepare_engine(source, tmp_path / "engine")
    record = verify_engine(output)
    assert record["base_commit"] == pin()["base_commit"]
    assert prepare_engine(source, output) == output
    assert (
        subprocess.check_output(["git", "-C", str(source), "status", "--porcelain"])
        == before
    )
    # Editable installation adds metadata without changing engine source.
    metadata = output / "python/sglang.egg-info"
    metadata.mkdir(exist_ok=True)
    (metadata / "PKG-INFO").write_text("generated by pip")
    assert verify_engine(output)["base_commit"] == record["base_commit"]
    (output / "python/sglang/__init__.py").write_text("changed")
    with pytest.raises(ValueError, match="files changed"):
        prepare_engine(source, output)


def test_dependency_prepare_requires_explicit_fetch_and_separate_output(tmp_path):
    with pytest.raises(FileNotFoundError):
        prepare_engine(tmp_path / "missing", tmp_path / "output")
    with pytest.raises(ValueError, match="separate"):
        prepare_engine(tmp_path / "source", tmp_path / "source/output")
